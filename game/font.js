/* ------------------------------------------------------------------------
   5×7 bitmap font for world labels (gate names, monolith labels, prompts).
   Uppercase only; lowercase maps to uppercase. Advance is 6px (5 + 1).
   Panel copy never uses this — it is a normal web font in the DOM.

   Each glyph is 7 rows of 5 bits. Coloured atlases are baked lazily, one
   per colour, so drawing text is a run of drawImage calls.
   ------------------------------------------------------------------------ */

(function () {
  "use strict";

  var G = (window.G = window.G || {});

  var GLYPHS = {
    " ": "00000 00000 00000 00000 00000 00000 00000",
    A: "01110 10001 10001 11111 10001 10001 10001",
    B: "11110 10001 10001 11110 10001 10001 11110",
    C: "01110 10001 10000 10000 10000 10001 01110",
    D: "11110 10001 10001 10001 10001 10001 11110",
    E: "11111 10000 10000 11110 10000 10000 11111",
    F: "11111 10000 10000 11110 10000 10000 10000",
    G: "01110 10001 10000 10111 10001 10001 01111",
    H: "10001 10001 10001 11111 10001 10001 10001",
    I: "01110 00100 00100 00100 00100 00100 01110",
    J: "00111 00010 00010 00010 00010 10010 01100",
    K: "10001 10010 10100 11000 10100 10010 10001",
    L: "10000 10000 10000 10000 10000 10000 11111",
    M: "10001 11011 10101 10101 10001 10001 10001",
    N: "10001 10001 11001 10101 10011 10001 10001",
    O: "01110 10001 10001 10001 10001 10001 01110",
    P: "11110 10001 10001 11110 10000 10000 10000",
    Q: "01110 10001 10001 10001 10101 10010 01101",
    R: "11110 10001 10001 11110 10100 10010 10001",
    S: "01111 10000 10000 01110 00001 00001 11110",
    T: "11111 00100 00100 00100 00100 00100 00100",
    U: "10001 10001 10001 10001 10001 10001 01110",
    V: "10001 10001 10001 10001 10001 01010 00100",
    W: "10001 10001 10001 10101 10101 10101 01010",
    X: "10001 10001 01010 00100 01010 10001 10001",
    Y: "10001 10001 01010 00100 00100 00100 00100",
    Z: "11111 00001 00010 00100 01000 10000 11111",
    "0": "01110 10001 10011 10101 11001 10001 01110",
    "1": "00100 01100 00100 00100 00100 00100 01110",
    "2": "01110 10001 00001 00010 00100 01000 11111",
    "3": "11111 00010 00100 00010 00001 10001 01110",
    "4": "00010 00110 01010 10010 11111 00010 00010",
    "5": "11111 10000 11110 00001 00001 10001 01110",
    "6": "00110 01000 10000 11110 10001 10001 01110",
    "7": "11111 00001 00010 00100 01000 01000 01000",
    "8": "01110 10001 10001 01110 10001 10001 01110",
    "9": "01110 10001 10001 01111 00001 00010 01100",
    "!": "00100 00100 00100 00100 00100 00000 00100",
    '"': "01010 01010 00000 00000 00000 00000 00000",
    "#": "01010 01010 11111 01010 11111 01010 01010",
    "%": "11000 11001 00010 00100 01000 10011 00011",
    "&": "01100 10010 10100 01000 10101 10010 01101",
    "'": "00100 00100 01000 00000 00000 00000 00000",
    "(": "00010 00100 01000 01000 01000 00100 00010",
    ")": "01000 00100 00010 00010 00010 00100 01000",
    "+": "00000 00100 00100 11111 00100 00100 00000",
    ",": "00000 00000 00000 00000 01100 00100 01000",
    "-": "00000 00000 00000 11111 00000 00000 00000",
    ".": "00000 00000 00000 00000 00000 01100 01100",
    "/": "00001 00001 00010 00100 01000 10000 10000",
    ":": "00000 01100 01100 00000 01100 01100 00000",
    "<": "00010 00100 01000 10000 01000 00100 00010",
    ">": "01000 00100 00010 00001 00010 00100 01000",
    "?": "01110 10001 00001 00010 00100 00000 00100",
    "|": "00100 00100 00100 00100 00100 00100 00100",
    "·": "00000 00000 00000 01100 01100 00000 00000",
    "—": "00000 00000 00000 11111 00000 00000 00000",
    "↑": "00100 01110 10101 00100 00100 00100 00100",
    "→": "00000 00100 00010 11111 00010 00100 00000",
    "←": "00000 00100 01000 11111 01000 00100 00000"
  };

  var CHARS = Object.keys(GLYPHS);
  var INDEX = {};
  CHARS.forEach(function (c, i) {
    INDEX[c] = i;
  });

  var CW = 5;
  var CH = 7;
  var ADV = 6;
  var atlases = {};

  function atlas(color) {
    if (atlases[color]) return atlases[color];
    var c = document.createElement("canvas");
    c.width = CHARS.length * CW;
    c.height = CH;
    var ctx = c.getContext("2d");
    ctx.fillStyle = color;
    CHARS.forEach(function (ch, i) {
      var rows = GLYPHS[ch].split(" ");
      for (var y = 0; y < CH; y++) {
        for (var x = 0; x < CW; x++) {
          if (rows[y].charAt(x) === "1") ctx.fillRect(i * CW + x, y, 1, 1);
        }
      }
    });
    atlases[color] = c;
    return c;
  }

  function width(text, scale) {
    return text.length ? (text.length * ADV - 1) * (scale || 1) : 0;
  }

  /* draw(ctx, text, x, y, {color, scale, shadow, align})
     align: "left" | "center" | "right". Coordinates are rounded so text
     never lands on a half pixel. */
  function draw(ctx, text, x, y, opts) {
    opts = opts || {};
    var s = opts.scale || 1;
    var str = String(text).toUpperCase();
    var w = width(str, s);
    if (opts.align === "center") x -= w / 2;
    else if (opts.align === "right") x -= w;
    x = Math.round(x);
    y = Math.round(y);
    if (opts.shadow) paint(ctx, str, x + s, y + s, opts.shadow, s);
    paint(ctx, str, x, y, opts.color || G.PAL.j, s);
  }

  function paint(ctx, str, x, y, color, s) {
    var a = atlas(color);
    for (var i = 0; i < str.length; i++) {
      var idx = INDEX[str.charAt(i)];
      if (idx === undefined) idx = INDEX["?"];
      if (str.charAt(i) !== " ") {
        ctx.drawImage(a, idx * CW, 0, CW, CH, x + i * ADV * s, y, CW * s, CH * s);
      }
    }
  }

  G.font = { draw: draw, width: width, height: CH };
})();
